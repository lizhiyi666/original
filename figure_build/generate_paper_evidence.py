"""Render two appendix tables from sealed JSON (read-only inputs, no model imports).

Also checks that v2/v3 screening and confirmed-candidate override ranks agree.
This audits stored metrics; it does not recompute metrics or launch experiments.
"""
import hashlib
import json
import math
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "experiment_runs"
OUT = ROOT / "paper-www2027/tables"
METRICS = ("Distance", "Radius", "CategoryTransition", "DailyLoc", "Category", "G-RANK")


def read(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def override_rank(confirm):
    ranks = []
    for label, candidate in confirm["results"].items():
        ratios = []
        for city, rows in candidate["cities"].items():
            base = confirm["baselines"][city]["rows"]
            for key in METRICS:
                a = mean(r["metrics"][key] for r in rows)
                b = mean(r["no_projection"][key] for r in base)
                ratios.append(a / max(b, 1e-12))
        cfg = candidate["config"]
        ranks.append((label, [max(ratios), mean(ratios), cfg["constraint_scale"],
            cfg["category_distribution_weight"], cfg["poi_distribution_weight"]]))
    return sorted(ranks, key=lambda row: row[1])


def main():
    source = RUNS / "ny-ist-distribution-balanced-v1-20261012"
    screen, confirm = read(source / "screen-selection.json"), read(source / "confirm-selection.json")
    v3path = RUNS / "ny-ist-distribution-balanced-v1-eval-v3-20261013-linux/summary.json"
    v3 = read(v3path)
    selected = read(RUNS / "ny-ist-distribution-best-formal-v1-20261013/selected-candidate.json")
    assert hashlib.sha256(v3path.read_bytes()).hexdigest() == selected["selection_files"]["summary.json"]
    ranking = screen["selection"]["ranking"]
    assert len(ranking) == 18
    assert [r["label"] for r in ranking] == [r["label"] for r in v3["screen"]["selection"]["ranking"]]
    r2, r3 = override_rank(confirm), override_rank(v3["confirm"])
    assert [r[0] for r in r2] == [r[0] for r in r3] == [r["label"] for r in selected["ranking"]]
    assert not confirm["selection"]["ranking"] and not v3["confirm"]["selection"]["ranking"]
    assert confirm["selection"]["failures"] == v3["confirm"]["selection"]["failures"]
    for (_, actual), expected in zip(r3, selected["ranking"]):
        assert all(math.isclose(a, b, abs_tol=1e-12) for a, b in zip(actual, expected["rank"]))
    lines = [
        "% Generated by figure_build/generate_paper_evidence.py; archived v2 screening only.",
        r"\begin{table}[t]", r"\centering\footnotesize", r"\setlength{\tabcolsep}{4pt}",
        r"\caption{Training-side screening (v2): maximum and mean of twelve city--metric JSD/JointGen ratios. $^*$ denotes the two candidates sent to three-seed confirmation, not passage of its distribution gates.}",
        r"\label{tab:grid}", r"\begin{tabular}{rrrrrr}", r"\toprule",
        r"Rank & $\rho$ & $\lambda$ & $\beta$ & Max & Mean \\", r"\midrule"]
    for i, row in enumerate(ranking, 1):
        vals = row["rank"]
        star = "^{*}" if row["label"] in confirm["results"] else ""
        lines.append(f"${i}{star}$ & {vals[2]:g} & {vals[3]:g} & {vals[4]:g} & {vals[0]:.4f} & {vals[1]:.4f}" + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    (OUT / "calibration-grid.tex").write_text("\n".join(lines)+"\n", encoding="utf-8")
    speed = read(RUNS / "pcdg-geo-v1-tol10-20261010/speed/confirm-r2-b0.1-summary.json")["200"]
    lines = ["% Archived selected-geometry qualification; denominator is projection Full.",
        r"\begin{table}[t]", r"\centering\footnotesize", r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Selected 200-step geometry qualification. Median seconds per 64-sequence spatial batch; ratio = Full+Geo / projection Full.}",
        r"\label{tab:cost}", r"\begin{tabular}{llrrr}"]
    lines += [r"\toprule", r"City & Batch & Full & Full+Geo & Ratio \\", r"\midrule"]
    for city, short in [("NewYork_PO1_OOD", "NY"), ("Istanbul_PO1_OOD", "IST")]:
        for case in ("ordinary", "long"):
            row = speed[f"{city}/{case}"]
            assert row["state"] == "complete"
            assert math.isclose(row["augmented"]/row["base"], row["ratio"], abs_tol=1e-12)
            lines.append(f"{short} & {case} & {row['base']:.3f} & {row['augmented']:.3f} & {row['ratio']:.4f}" + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (OUT / "cost.tex").write_text("\n".join(lines)+"\n", encoding="utf-8")
    print("All 18 screening ranks unchanged; failed confirmation gates unchanged.")
    print("Confirmed override ranks (v2 then v3):", r2, r3)
    print("Wrote calibration-grid.tex and cost.tex from sealed values.")


if __name__ == "__main__":
    main()
